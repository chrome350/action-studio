import assert from 'node:assert/strict';
import {gridVideoPolicy,gridResizeMask,gridPublishVideoFrame,gridWaitForFullFrame} from '../source/video-performance.js';
const video=Object.assign(new EventTarget(),{tagName:'VIDEO',paused:false,currentTime:1});
assert.equal(gridVideoPolicy(video).size,1080);
assert.ok(gridVideoPolicy(video,100).interval>=250,'preview leaves time for other work');
video.paused=true;assert.equal(gridVideoPolicy(video).size,1080);
video.paused=false;video.gridExporting=true;assert.equal(gridVideoPolicy(video).size,1080);
video.gridExporting=false;video.gridFullFrame=true;assert.equal(gridVideoPolicy(video).size,1080);
assert.equal(gridVideoPolicy({tagName:'IMG'}).size,1080);
const mask=new Uint8ClampedArray(600*600);mask[100*600+200]=255;
assert.equal(gridResizeMask(mask,600),mask);assert.equal(gridResizeMask(mask,300)[50*300+100],255);
assert.equal(gridResizeMask(mask,1080)[180*1080+360],255);
const waiting=gridWaitForFullFrame(video);gridPublishVideoFrame(video,300);assert.equal(video.gridNeedsFullFrame,true);
gridPublishVideoFrame(video,1080);await waiting;assert.equal(video.gridNeedsFullFrame,false);
video.currentTime=2;
let latestReady=false;
const newest=gridWaitForFullFrame(video).then(()=>{latestReady=true});
gridPublishVideoFrame(video,1080,1);
await Promise.resolve();
assert.equal(video.gridRenderedTime,1,'worker publishes the captured time, not the current decoder time');
assert.equal(video.gridNeedsFullFrame,true,'a stale worker frame cannot acknowledge a seek/export request');
assert.equal(latestReady,false,'full-frame waiter keeps waiting for the current captured time');
gridPublishVideoFrame(video,1080,2);await newest;
assert.equal(video.gridNeedsFullFrame,false);
await assert.rejects(gridWaitForFullFrame(video,1),/подготовить кадр/);
console.log('Video quality: adaptive budget, pause/export/image resolution, mask mapping and full-frame acknowledgement passed.');
