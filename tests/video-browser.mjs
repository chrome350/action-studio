// Run with GRID_PLAYWRIGHT_PATH pointing to Playwright, and a local MP4 argument.
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {pathToFileURL,fileURLToPath} from 'node:url';
import path from 'node:path';
import fs from 'node:fs/promises';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.GRID_PLAYWRIGHT_PATH||'playwright');
const fixture=process.argv[2];if(!fixture)throw Error('Pass a local test video path.');
const root=fileURLToPath(new URL('../',import.meta.url));
const browser=await chromium.launch({channel:'chrome',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto(pathToFileURL(path.join(root,'Grid Studio.html')).href);
 const upload=page.locator('input[type=file]');await upload.setInputFiles(fixture);
 await page.waitForFunction(()=>{const slider=document.querySelector('[aria-label="Позиция видео"]');return slider&&!slider.disabled});
 await page.getByRole('combobox',{name:'Режим эффекта'}).selectOption('letters');
 await page.waitForFunction(()=>document.querySelector('.stage > canvas').width===300);
 assert.equal(await page.getByRole('button',{name:'Пауза видео',exact:true}).count(),0,'no duplicate pause control');
 assert.equal(await page.getByText('Предпросмотр без звука.',{exact:false}).count(),0,'explanation removed');
 await page.locator('.stage').click({position:{x:300,y:300}});await page.keyboard.press('Space');
 const canvas=page.locator('.stage > canvas').first();await page.waitForFunction(()=>document.querySelector('.stage > canvas').width===600);await page.waitForTimeout(100);
 const still=await canvas.evaluate(c=>c.toDataURL());await page.waitForTimeout(200);
 assert.equal(await canvas.evaluate(c=>c.toDataURL()),still,'space freezes canvas');
 await page.getByRole('slider',{name:'Позиция видео'}).fill('1');await page.waitForTimeout(300);
 assert.notEqual(await canvas.evaluate(c=>c.toDataURL()),still,'seek paints a new frame');
 assert.equal(await canvas.evaluate(c=>c.width),600,'seek uses full resolution');
 const pngDownload=page.waitForEvent('download');await page.getByRole('button',{name:'Сохранить PNG'}).click();
 const png=await pngDownload;assert.ok(png.suggestedFilename().endsWith('.png'));
 assert.equal(await canvas.evaluate(c=>c.width),600,'PNG waits for full resolution');
 const download=page.waitForEvent('download',{timeout:30000});
 await page.getByRole('button',{name:'Экспорт видео',exact:true}).click();
 await page.waitForTimeout(1200);
 assert.equal(await canvas.evaluate(c=>c.width),600,'export uses full resolution');
 await page.getByRole('button',{name:'Завершить и сохранить'}).click();
 const file=await download;const output=path.join('/tmp',file.suggestedFilename());await file.saveAs(output);
 assert.ok((await fs.stat(output)).size>1000,'recording is not empty');
 await page.getByRole('link',{name:'Скачать готовое видео'}).waitFor();
 await upload.setInputFiles(path.join(root,'flowers.png'));await page.waitForTimeout(200);
 assert.equal(await page.locator('.video-controls').count(),0,'image mode restored');
 await upload.setInputFiles({name:'invalid.mp4',mimeType:'video/mp4',buffer:Buffer.from('invalid')});
 await page.getByRole('alert').filter({hasText:'Не удалось открыть видео'}).waitFor();
 await upload.setInputFiles(fixture);await page.waitForFunction(()=>{const slider=document.querySelector('[aria-label="Позиция видео"]');return slider&&!slider.disabled});
 await page.setViewportSize({width:390,height:844});await page.waitForTimeout(200);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'mobile has no horizontal overflow');
 await page.screenshot({path:'/tmp/grid-video-mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('PASS: local video, Letters, space, seek, early export, image replacement, invalid video recovery, mobile layout. Export:',output);
}finally{await browser.close()}
