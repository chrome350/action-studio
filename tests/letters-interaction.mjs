import assert from 'node:assert/strict';
import {createLettersInteraction,drawLettersInteraction} from '../source/letters-interaction.js';
const state=createLettersInteraction();
const tile={left:50,top:50,w:10,h:10,ox:0,oy:0,vx:0,vy:0};
state.cells=[{image:{width:200,height:200},x:100,y:100,tiles:[tile],background:'#000'}];
const ctx={save(){},restore(){},beginPath(){},rect(){},clip(){},fillRect(){},drawImage(){}};
state.pointer={x:145,y:155,down:false};
for(let t=16;t<1000;t+=16)drawLettersInteraction(ctx,state,true,100,45,false,t);
assert.ok(tile.ox>30);assert.equal(tile.oy,0);
state.pointer=null;
for(let t=1000;t<4000;t+=16)drawLettersInteraction(ctx,state,true,100,45,false,t);
assert.ok(Math.abs(tile.ox)<.001,'returns to origin after pointer leaves');
state.pointer={x:145,y:155,down:true};
drawLettersInteraction(ctx,state,true,100,45,false,4016);assert.ok(tile.ox>0);
drawLettersInteraction(ctx,state,true,100,45,true,4032);assert.equal(tile.ox,0);
drawLettersInteraction(ctx,state,false,100,45,false,4048);assert.equal(tile.ox,0);
console.log('Letters interaction: global pointer position, repulsion, return, reduced motion and toggle passed.');
// Hidden grid clips the entire Letters region once, and clears before any glyph is drawn.
const events=[];
const recording={...ctx,clip(){events.push('clip')},fillRect(){events.push('clear')},drawImage(){events.push('glyph')}};
const seam=createLettersInteraction();
seam.cells=[0,100].map(x=>({x,y:0,image:{width:100,height:100},background:'#000',tiles:[{left:0,top:0,w:5,h:10,anchorX:100,anchorY:50,ox:0,oy:0,vx:0,vy:0}]}));
seam.pointer={x:90,y:50};
drawLettersInteraction(recording,seam,true,100,45,false,16,false);
assert.equal(events.filter(e=>e==='clip').length,1);
assert.ok(events.lastIndexOf('clear')<events.indexOf('glyph'));
assert.equal(seam.cells[0].tiles[0].ox,seam.cells[1].tiles[0].ox,'split glyph parts move together');
events.length=0;
drawLettersInteraction(recording,seam,true,100,45,false,32,true);
assert.equal(events.filter(e=>e==='clip').length,2);
console.log('Hidden grid: shared mask, background ordering and joined glyph movement passed.');
